const { test } = require('node:test');
const assert = require('node:assert/strict');
const { _electron: electron } = require('playwright-core');
const fs = require('node:fs/promises');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

test('native player: one local window, audio, catalogue, queue, seeking, MPRIS and IPC', { timeout: 60000 }, async () => {
  const root = path.resolve(__dirname, '..');
  const out = path.join(root, 'test-results');
  await fs.mkdir(out, { recursive: true });
  const profile = await fs.mkdtemp('/tmp/opencode/yamp-test-');
  const samples = 8000 * 20, data = Buffer.alloc(44 + samples * 2);
  data.write('RIFF', 0); data.writeUInt32LE(data.length - 8, 4); data.write('WAVEfmt ', 8);
  data.writeUInt32LE(16, 16); data.writeUInt16LE(1, 20); data.writeUInt16LE(1, 22);
  data.writeUInt32LE(8000, 24); data.writeUInt32LE(16000, 28); data.writeUInt16LE(2, 32); data.writeUInt16LE(16, 34);
  data.write('data', 36); data.writeUInt32LE(samples * 2, 40);
  await fs.writeFile(path.join(out, 'silence.wav'), data);
  const app = await electron.launch({ args: [root], env: { ...process.env, YAMP_TEST: '1', YAMP_TEST_PROFILE: profile, ELECTRON_RUN_AS_NODE: '' } });
  app.process().stderr.on('data', data => process.stderr.write(data));
  try {
    const ui = await app.firstWindow();
    await ui.waitForURL('**/src/index.html');
    await ui.waitForFunction(() => document.querySelectorAll('#queue li').length === 2);
    assert.equal(app.windows().length, 1, 'no hidden website window');
    assert.equal(await ui.evaluate(() => typeof window.require), 'undefined');
    const invoke = (action, value) => ui.evaluate(([a, v]) => window.yamp.command(a, v), [action, value]);
    const initial = (await invoke('state')).state;
    assert.equal(initial.authenticating, false, 'Chrome is not running');
    assert.equal((await invoke('volume', 2)).ok, false);
    assert.equal((await invoke('execute', 'process.exit()')).ok, false);
    assert.equal((await invoke('open-item', { index: 0, revision: -1 })).ok, false);
    assert.equal((await invoke('volume', 0.35)).ok, true);
    await ui.locator('#queue .item-main').first().click();
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'PLAYING');
    assert.equal(execFileSync('playerctl', ['-p', 'yamp_test', 'status'], { encoding: 'utf8' }).trim(), 'Playing');
    await invoke('minimize');
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), false);
    assert.equal(execFileSync('playerctl', ['-p', 'yamp_test', 'status'], { encoding: 'utf8' }).trim(), 'Playing');
    await app.evaluate(({ app }) => app.emit('second-instance'));
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), true);
    execFileSync('playerctl', ['-p', 'yamp_test', 'pause']);
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'PAUSED');
    assert.equal((await invoke('seek', 7)).ok, true);
    await ui.waitForFunction(() => document.querySelector('#time').textContent === '00:07');
    await ui.locator('[data-action=next]').click();
    await ui.waitForFunction(() => document.querySelector('#title').textContent === 'Segunda canción' && document.querySelector('#status').textContent === 'PLAYING');
    await invoke('show-queue');
    await ui.locator('#queue .item-main').first().click();
    await ui.waitForFunction(() => document.querySelector('#title').textContent === 'Primera canción' && document.querySelector('#status').textContent === 'PLAYING');
    await ui.locator('#shuffle').click();
    await ui.waitForFunction(() => document.querySelector('#shuffle').classList.contains('active'));
    await ui.locator('#repeat').click();
    assert.equal((await invoke('state')).state.repeat, 'all');
    await ui.locator('#repeat').click();
    assert.equal((await invoke('state')).state.repeat, 'one');
    await ui.locator('#toggle-queue').click();
    assert.equal(await ui.locator('#playlist').isVisible(), false);
    await ui.screenshot({ path: path.join(out, 'compact.png') });
    await ui.locator('#toggle-queue').click();
    await ui.screenshot({ path: path.join(out, 'player.png') });
    assert.equal((await invoke('queue', 99)).ok, false);
    await invoke('search', '<img src=x onerror=alert(1)>');
    assert.equal(await ui.locator('#list-title').textContent(), '<img src=x onerror=alert(1)>');
    assert.equal(await ui.locator('#list-title img').count(), 0);
    await ui.locator('#queue .add-item').first().click();
    assert.equal((await invoke('state')).state.queue.length, 3);
    await invoke('stop');
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'PAUSED');
    assert.equal((await invoke('state')).state.playing, false);
    assert.equal((await invoke('state')).state.authenticating, false);
    assert.equal(app.windows().length, 1);
  } finally { await app.close(); await fs.rm(profile, { recursive: true, force: true }); }
});
