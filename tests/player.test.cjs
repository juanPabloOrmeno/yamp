const { test } = require('node:test');
const assert = require('node:assert/strict');
const { _electron: electron } = require('playwright-core');
const fs = require('node:fs/promises');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

test('native player: one local window, audio, catalogue, queue, seeking, MPRIS and IPC', { timeout: 60000 }, async () => {
  const root = path.resolve(__dirname, '..');
  const out = path.join(root, 'test-results');
  await fs.mkdir(out, { recursive: true });
  const profile = await fs.mkdtemp(path.join(require('node:os').tmpdir(), 'yamp-test-'));
  const samples = 8000 * 20, data = Buffer.alloc(44 + samples * 2);
  data.write('RIFF', 0); data.writeUInt32LE(data.length - 8, 4); data.write('WAVEfmt ', 8);
  data.writeUInt32LE(16, 16); data.writeUInt16LE(1, 20); data.writeUInt16LE(1, 22);
  data.writeUInt32LE(8000, 24); data.writeUInt32LE(16000, 28); data.writeUInt16LE(2, 32); data.writeUInt16LE(16, 34);
  data.write('data', 36); data.writeUInt32LE(samples * 2, 40);
  await fs.writeFile(path.join(out, 'silence.wav'), data);
  await fs.mkdir(path.join(profile, 'audio'));
  await fs.writeFile(path.join(profile, 'audio', 'offline0001.audio'), data);
  await fs.writeFile(path.join(profile, 'audio', 'offline0001.json'), JSON.stringify({ id: 'offline0001', kind: 'song', title: 'Canción local', artist: 'Sin conexión', bytes: data.length, duration: 20 }));
  const app = await electron.launch({ args: [root], env: { ...process.env, YAMP_TEST: '1', YAMP_TEST_PROFILE: profile, ELECTRON_RUN_AS_NODE: '' } });
  app.process().stderr.on('data', data => process.stderr.write(data));
  try {
    const ui = await app.firstWindow();
    await ui.waitForURL('**/src/index.html');
    await ui.waitForFunction(() => document.querySelectorAll('#queue li').length === 2);
    assert.equal(app.windows().length, 1, 'no hidden website window');
    assert.equal(await ui.evaluate(() => typeof window.require), 'undefined');
    const invoke = (action, value) => ui.evaluate(([a, v]) => window.yamp.command(a, v), [action, value]);
    const initial = (await invoke('state')).state;
    assert.equal(initial.authenticating, false, 'Chrome is not running');
    assert.equal((await invoke('volume', 2)).ok, false);
    assert.equal((await invoke('execute', 'process.exit()')).ok, false);
    assert.equal((await invoke('open-item', { index: 0, revision: -1 })).ok, false);
    assert.equal((await invoke('volume', 0.35)).ok, true);
    await ui.locator('#queue .item-main').first().click();
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'PLAYING');
    assert.equal((await invoke('state')).state.queue.length, 1, 'playing a result queues only the selected song');
    await ui.locator('#queue .add-item').nth(1).click();
    assert.equal((await invoke('state')).state.queue.length, 2, 'adding another result preserves the queue');
    if (process.platform === 'linux') assert.equal(execFileSync('playerctl', ['-p', 'yamp_test', 'status'], { encoding: 'utf8' }).trim(), 'Playing');
    await invoke('minimize');
    if (process.platform === 'darwin') {
      await ui.waitForTimeout(500);
      assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isMinimized()), true);
      assert.equal((await invoke('state')).state.playing, true);
    } else {
      assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), false);
      assert.equal(execFileSync('playerctl', ['-p', 'yamp_test', 'status'], { encoding: 'utf8' }).trim(), 'Playing');
    }
    await app.evaluate(({ app }) => app.emit('second-instance'));
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), true);
    if (process.platform === 'darwin') {
      await app.evaluate(({ Menu }) => Menu.getApplicationMenu().items.find(item => item.label === 'Reproducción').submenu.items[0].click());
    } else execFileSync('playerctl', ['-p', 'yamp_test', 'pause']);
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'PAUSED');
    assert.equal((await invoke('seek', 7)).ok, true);
    await ui.waitForFunction(() => document.querySelector('#time').textContent === '00:07');
    await ui.locator('[data-action=next]').click();
    await ui.waitForFunction(() => document.querySelector('#title').textContent === 'Segunda canción' && document.querySelector('#status').textContent === 'PLAYING');
    await invoke('show-queue');
    await ui.locator('#queue .item-main').first().click();
    await ui.waitForFunction(() => document.querySelector('#title').textContent === 'Primera canción' && document.querySelector('#status').textContent === 'PLAYING');
    await ui.locator('#shuffle').click();
    await ui.waitForFunction(() => document.querySelector('#shuffle').classList.contains('active'));
    await ui.locator('#repeat').click();
    assert.equal((await invoke('state')).state.repeat, 'all');
    await ui.locator('#repeat').click();
    assert.equal((await invoke('state')).state.repeat, 'one');
    await ui.locator('#toggle-queue').click();
    assert.equal(await ui.locator('#playlist').isVisible(), false);
    await ui.screenshot({ path: path.join(out, 'compact.png') });
    await ui.locator('#toggle-queue').click();
    await ui.screenshot({ path: path.join(out, 'player.png') });
    assert.equal((await invoke('queue', 99)).ok, false);
    await invoke('search', '<img src=x onerror=alert(1)>');
    assert.equal(await ui.locator('#list-title').textContent(), '<img src=x onerror=alert(1)>');
    assert.equal(await ui.locator('#list-title img').count(), 0);
    await ui.locator('#queue .add-item').first().click();
    assert.equal((await invoke('state')).state.queue.length, 3);
    await invoke('show-queue');
    await ui.locator('#queue .add-item').last().click();
    await ui.waitForFunction(() => document.querySelectorAll('#queue .item-main').length === 2);
    assert.equal((await invoke('state')).state.queue.length, 2);
    assert.equal((await invoke('remove-queue', -1)).ok, false);
    await ui.locator('#save-playlist').click();
    await ui.locator('#playlist-name').fill('Mi cola favorita');
    await ui.locator('#confirm-playlist').click();
    await ui.waitForFunction(() => document.querySelector('#playlists-message').textContent === 'Playlist guardada en YAMP.');
    const savedQueue = (await invoke('state')).state.queue.map(row => row.id);
    await ui.locator('#close-playlists').click();
    await ui.locator('#clear-queue').click();
    await ui.waitForFunction(() => document.querySelectorAll('#queue .item-main').length === 0);
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'READY');
    assert.equal((await invoke('state')).state.playing, false);
    await ui.locator('#show-playlists').click();
    await ui.locator('#saved-playlists button').first().click();
    await ui.waitForFunction(() => document.querySelectorAll('#queue .item-main').length === 2);
    assert.deepEqual((await invoke('state')).state.queue.map(row => row.id), savedQueue);
    await ui.locator('#show-playlists').click();
    await ui.getByRole('button', { name: 'Eliminar playlist Mi cola favorita', exact: true }).click();
    await ui.waitForFunction(() => document.querySelectorAll('#saved-playlists .saved-playlist').length === 0);
    assert.deepEqual((await invoke('state')).state.queue.map(row => row.id), savedQueue);
    await ui.locator('#close-playlists').click();
    await ui.locator('#clear-queue').click();
    await invoke('stop');
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'READY');
    assert.equal((await invoke('state')).state.playing, false);
    assert.equal((await invoke('state')).state.authenticating, false);
    await ui.locator('[data-action=history]').click();
    await ui.waitForFunction(() => document.querySelector('#list-title').textContent === 'HISTORIAL · RECIENTES');
    assert.equal(await ui.locator('#queue .item-main').count(), 2);
    assert.match(await ui.locator('#queue .item-main').first().textContent(), /Primera canción/);
    await ui.locator('#queue .add-item').first().click();
    assert.equal((await invoke('state')).state.queue.length, 1);
    await ui.locator('#queue .item-main').first().click();
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'PLAYING');
    await ui.locator('#clear-history').click();
    await ui.waitForFunction(() => document.querySelectorAll('#queue .item-main').length === 0);
    assert.equal((await invoke('state')).state.queue.length, 2);
    assert.equal((await invoke('state')).state.playing, true);
    assert.equal(app.windows().length, 1);
    await ui.locator('[data-action=local]').click();
    await ui.waitForFunction(() => document.querySelector('#list-title').textContent === 'GUARDADAS · SIN CONEXIÓN');
    assert.equal(await ui.locator('#queue .item-main').count(), 1);
    await ui.locator('#queue .item-main').first().click();
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'PLAYING' && document.querySelector('#title').textContent === 'Canción local');
    assert.equal((await invoke('state')).state.local, true);
    await ui.screenshot({ path: path.join(out, 'offline.png') });
    await ui.locator('#manage-local').click();
    await ui.locator('#local-select-all').check();
    await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }); });
    await ui.locator('#backup-local').click();
    await ui.waitForFunction(() => document.querySelector('#local-message').textContent === 'Respaldo cancelado.');
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, profile);
    await ui.locator('#backup-local').click();
    await ui.waitForFunction(() => document.querySelector('#local-message').textContent.includes('respaldada(s)'));
    const backupName = (await fs.readdir(profile)).find(name => name.startsWith('YAMP-respaldo-'));
    assert.ok(backupName);
    assert.deepEqual(await fs.readFile(path.join(profile, backupName, 'offline0001.audio')), data);
    await ui.screenshot({ path: path.join(out, 'local-manager.png') });
    await ui.locator('#delete-local').click();
    await ui.waitForFunction(() => document.querySelector('#local-summary').textContent === 'Todavía no hay canciones guardadas.');
    assert.equal(await ui.locator('#local-tracks input').count(), 0);
    assert.deepEqual(await fs.readFile(path.join(profile, backupName, 'offline0001.audio')), data);
    await ui.locator('#close-manager').click();
    assert.equal(await ui.locator('#queue .item-main').count(), 0);
    await ui.locator('#manage-local').click();
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, path.join(profile, backupName));
    await ui.locator('#restore-local').click();
    await ui.waitForFunction(() => document.querySelector('#local-message').textContent.includes('1 canción(es) restaurada(s)'));
    await ui.locator('#download-library').click();
    await ui.waitForFunction(() => document.querySelector('#library-progress').textContent.includes('Bibliotecas guardadas.'));
    assert.match(await ui.locator('#library-progress').textContent(), /1 existentes/);
    assert.equal(await ui.locator('#local-tracks input').count(), 1);
    await ui.screenshot({ path: path.join(out, 'local-manager-restore.png') });
    await ui.locator('#close-manager').click();
    await ui.locator('#queue .item-main').first().click();
    await ui.waitForFunction(() => document.querySelector('#status').textContent === 'PLAYING');
    assert.equal((await invoke('state')).state.local, true);
    const beforeAll = (await invoke('state')).state;
    await invoke('search', 'Todas las canciones');
    await ui.locator('#enqueue-all').click();
    await ui.waitForFunction(() => !document.querySelector('#enqueue-all').disabled);
    const afterAll = (await invoke('state')).state;
    assert.equal(afterAll.queue.length, beforeAll.queue.length + 2);
    assert.equal(afterAll.id, beforeAll.id);
    assert.equal(afterAll.playing, true);
    assert.deepEqual(afterAll.queue.slice(-2).map(row => row.id), ['test0000001', 'test0000002']);
    assert.equal((await invoke('enqueue-all', { mode: 'catalogue', revision: -1 })).ok, false);
  } finally { await app.close(); await fs.rm(profile, { recursive: true, force: true }); }
});
